# ngpu_core : reprise de Skate1Native tools/d3d/compile_native_shaders.sh (commit 81805f51), chemins adaptes.
# Compile the core's own shaders (ngpu_core/src/shaders/*.hlsl) to SPIR-V embedded in
# ngpu_core/src/shaders/native_shaders.h, with the DXC of XenosRecomp (tools/build_xenosrecomp.sh -> work/XenosRecomp-unified).
set -euo pipefail
cd "$(dirname "$0")/../.."  # ngpu_core/
XR="${XENOSRECOMP:-$PWD/../work/XenosRecomp-unified}"
DXC="$XR/thirdparty/dxc-bin/bin/x64/dxc-linux"
export LD_LIBRARY_PATH="$XR/thirdparty/dxc-bin/lib/x64"
OUT=${OUT:-src/shaders/native_shaders.h}
TMP=$(mktemp -d)
compile() {  # name source entry profile
  "$DXC" -spirv -fspv-target-env=vulkan1.1 -E "$3" -T "$4" -Fo "$TMP/$1.spv" "$2" >/dev/null
  python3 - "$TMP/$1.spv" "$1" >> "$OUT" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
print(f"inline constexpr uint8_t k_{sys.argv[2]}[] = {{")
for i in range(0, len(data), 16):
    print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
print("};")
PY
}
printf '// Generated by tools/d3d/compile_native_shaders.sh - do not edit.\n#pragma once\n\n#include <cstdint>\n\n' > "$OUT"
compile resolve_vs src/shaders/resolve.hlsl VSMain vs_6_0
compile resolve_ps src/shaders/resolve.hlsl PSMain ps_6_0
compile pack_ps src/shaders/resolve.hlsl PSPack ps_6_0
rm -rf "$TMP"
echo "wrote $OUT"
